// A1 vocabulary, part 3 — the two themes that are not about a topic.
//
// The other twelve A1 themes are topical (Wohnen, Essen, Kleidung), and that is
// exactly why they leak: a high-frequency verb like `bringen` or an adverb like
// `leider` belongs to no topic, so nothing owns it. Checking the town against
// the Goethe-Zertifikat A1 Wortliste made the hole measurable — of 427 listed
// words the A1 town had no card for, roughly 97 were verbs and 129 adjectives
// or adverbs, while the twelve topical decks between them held only 82 verbs,
// most of which happened to name their own theme (wohnen, essen, trinken).
//
// So these two decks are organised by what a word DOES rather than what it is
// about. Words are drawn from that list's gap; the English glosses, the hints
// and the Redemittel are written here.
//
// Note the Wortliste is the Goethe/telc A1 selection, not an ÖSD one — the ÖSD
// publishes no word list and defines A1 by the CEFR descriptors alone. It is
// used as a floor to cover, never a ceiling to trim to: it contains no Tür, no
// Fenster, no Stuhl, no Onkel.

